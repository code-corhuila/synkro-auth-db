-- Evidence of every committed ADMIN password reset: who reset whose password, and under which
-- idempotency key (HU-AUTH-19, ADR-021 Decision 4).
-- Failed or rejected attempts are not stored here: they belong to the security logs, because a
-- rolled-back reset must leave no row behind.
-- The row is also the idempotency record of the reset, written in the same transaction as the new
-- password and the revocation of the target's refresh tokens, so a key can never be recorded without
-- its effects. The key is scoped to its actor: another ADMIN using the same text is a different key.
-- No password, password hash, token or request body is stored here.
CREATE TABLE auth_schema.password_reset_audit (
  -- generated by Auth, like user_creation_audit.audit_id: no default, so a row cannot invent its own id
  audit_id          uuid        NOT NULL,
  operation         text        NOT NULL,
  -- the ADMIN from the validated access token; the use case checks the role when it acts, so a later
  -- role change never invalidates a record
  actor_user_id     uuid        NOT NULL,
  target_user_id    uuid        NOT NULL,
  idempotency_key   text        NOT NULL,
  outcome           text        NOT NULL,
  occurred_at       timestamptz NOT NULL,
  correlation_id    text        NOT NULL,
  CONSTRAINT pk_password_reset_audit PRIMARY KEY (audit_id),
  -- (actor, key) names one reset; its index also serves the actor foreign key
  CONSTRAINT uq_password_reset_audit_actor_key UNIQUE (actor_user_id, idempotency_key),
  CONSTRAINT chk_password_reset_audit_operation CHECK (operation = 'PASSWORD_RESET'),
  CONSTRAINT chk_password_reset_audit_outcome CHECK (outcome = 'SUCCESS'),
  CONSTRAINT chk_password_reset_audit_idempotency_key CHECK (char_length(idempotency_key) BETWEEN 8 AND 128),
  CONSTRAINT chk_password_reset_audit_correlation_id CHECK (char_length(correlation_id) >= 1),
  -- an administrator never resets their own password through this operation
  CONSTRAINT chk_password_reset_audit_not_self CHECK (actor_user_id <> target_user_id)
);
